/**
 * MSW handlers for the three explorer operations of `api/openapi.yaml`:
 * the settlements listing, the records listing, and the per-match detail the
 * settlement breakdown opens.
 *
 * Kept out of `handlers.ts` so this branch adds a file rather than rewriting a
 * shared one; `handlers.ts` spreads it in. Same rules as the file it joins:
 * contract-valid shapes and nothing else, money as integer paise, percentages
 * in basis points with integer floor division, and not a single float amount.
 *
 * THE TWO THINGS THIS FIXTURE EXISTS TO REPRODUCE.
 *
 * 1. A settlement that never closed. 15 of 166 on the 500-record runs, with a
 *    null tier, a null bank line and a null match — the rows a reviewer opens
 *    this listing to find, and the rows that had no way to reach the screen
 *    before it existed.
 *
 * 2. A T3 row whose columns do not add up. `net` is the bank credit and a T3
 *    match is precisely one where the reconstruction and the credit disagree
 *    within tolerance, so every T3 row here is 50 paise out and says so in its
 *    own evidence. A fixture where the arithmetic always closed would let a UI
 *    that silently balanced its columns look correct.
 */
